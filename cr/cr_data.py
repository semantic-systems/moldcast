"""
cr_data.py - the SparseCL contradiction-retrieval benchmarks, read exactly as their release does.

Data: https://huggingface.co/SparseCL/all-train-dev-test-data, files put in --data_dir (default ./data):
  training triples   arguana_training_final.csv / arguana_validation_final.csv
                     {hotpotqa,msmarco}_{train,dev}_gpt4_final.csv
                     three columns: anchor, its contradiction (positive), a similar passage (hard neg)
  retrieval splits   arguana_{train,dev,test}_retrieval_final.pkl
                     {hotpotqa,msmarco}_{train,dev,test}_retrieval_gpt4_final.pkl
                     three pickled objects in sequence: corpus {pid: {"text": ...}},
                     queries {qid: text}, qrels {qid: {pid: relevance}}

Protocol (as in their test_contradiction_faiss_final.py): the corpus is the UNION of the train,
dev and test corpora; queries and qrels come from the evaluated split; NDCG@10 and Recall@10.
"""
import csv
import math
import os
import pickle

DATASETS = ("arguana", "hotpotqa", "msmarco", "vitaminc")   # vitaminc: the symmetric benchmark
# built by build_vitaminc.py, in the same file format as hotpotqa/msmarco (the "gpt4" in its file
# names is only that naming convention: nothing in it is generated by GPT-4)


def triples_file(data_dir, dataset, part):
    """part: train | dev  (the CSVs used for training and for validation loss)."""
    if dataset == "arguana":
        name = {"train": "arguana_training_final.csv", "dev": "arguana_validation_final.csv"}[part]
    else:
        name = f"{dataset}_{part}_gpt4_final.csv"
    return os.path.join(data_dir, name)


def retrieval_file(data_dir, dataset, split):
    if dataset == "arguana":
        return os.path.join(data_dir, f"arguana_{split}_retrieval_final.pkl")
    return os.path.join(data_dir, f"{dataset}_{split}_retrieval_gpt4_final.pkl")


def load_triples(path):
    """-> list of (anchor, contradiction, hard_negative); the header row is skipped."""
    if not os.path.exists(path):
        raise SystemExit(f"missing {path}: download the SparseCL data into --data_dir")
    out = []
    with open(path, newline="", encoding="utf-8") as f:
        rows = csv.reader(f)
        header = next(rows)
        if len(header) < 3:
            raise SystemExit(f"{path}: expected 3 columns (anchor, contradiction, hard negative), "
                             f"found {len(header)}: {header}")
        for r in rows:
            if len(r) >= 3:
                out.append(tuple((x or " ").strip() or " " for x in r[:3]))
    return out


def load_split(data_dir, dataset, split):
    """-> corpus (union of all three splits), queries, qrels for `split`."""
    corpus = {}
    for part in ("train", "dev", "test"):
        path = retrieval_file(data_dir, dataset, part)
        if not os.path.exists(path):
            raise SystemExit(f"missing {path}: download the SparseCL data into --data_dir")
        with open(path, "rb") as f:
            corpus.update(pickle.load(f))
    with open(retrieval_file(data_dir, dataset, split), "rb") as f:
        pickle.load(f)
        queries = pickle.load(f)
        qrels = pickle.load(f)
    corpus = {str(k): (v.get("text", "") if isinstance(v, dict) else str(v)).strip()
              for k, v in corpus.items()}
    queries = {str(k): str(v).strip() for k, v in queries.items()}
    qrels = {str(q): {str(d): int(r) for d, r in rel.items()} for q, rel in qrels.items()}
    return corpus, queries, qrels


def evaluate(qrels, results, k=10, ignore_identical_ids=True):
    """NDCG@k and Recall@k exactly as BEIR's EvaluateRetrieval.evaluate computes them (which
    SparseCL calls): a result whose passage id equals the query id is dropped AFTER the top k were
    chosen (BEIR's default ignore_identical_ids=True, so such a query is scored on k - 1 results),
    then pytrec_eval scores each query that has results, and the mean is taken over those queries.
    The built-in fallback reproduces pytrec_eval's ndcg_cut / recall (used when it is missing)."""
    if ignore_identical_ids:
        results = {q: {d: s for d, s in r.items() if d != q} for q, r in results.items()}
    try:
        import pytrec_eval
        ev = pytrec_eval.RelevanceEvaluator(qrels, {f"ndcg_cut.{k}", f"recall.{k}"})
        scores = ev.evaluate({q: {d: float(s) for d, s in r.items()} for q, r in results.items()})
        n = max(len(scores), 1)
        ndcg = sum(s[f"ndcg_cut_{k}"] for s in scores.values()) / n
        rec = sum(s[f"recall_{k}"] for s in scores.values()) / n
        return {f"NDCG@{k}": ndcg, f"Recall@{k}": rec, "backend": "pytrec_eval"}
    except ImportError:
        pass
    ndcg = rec = 0.0
    scored = [q for q in qrels if q in results]        # pytrec_eval scores queries in both
    for q in scored:
        rel = qrels[q]
        ranked = sorted(results[q].items(), key=lambda x: (-x[1], x[0]))[:k]
        dcg = sum(rel.get(d, 0) / math.log2(i + 2) for i, (d, _) in enumerate(ranked))
        ideal = sorted((r for r in rel.values() if r > 0), reverse=True)[:k]
        idcg = sum(r / math.log2(i + 2) for i, r in enumerate(ideal))
        ndcg += dcg / idcg if idcg > 0 else 0.0
        n_rel = sum(1 for r in rel.values() if r > 0)
        rec += sum(1 for d, _ in ranked if rel.get(d, 0) > 0) / n_rel if n_rel else 0.0
    n = max(len(scored), 1)
    return {f"NDCG@{k}": ndcg / n, f"Recall@{k}": rec / n, "backend": "builtin"}
